// AutoConfigChecker is the gateway config check the AutoConfig controller runs
// over the endpoints it is about to write (configcheck.Checker).
type AutoConfigChecker interface {
	// Conflicts renders gw with replace in process and returns what the
	// render leaves out.
	Conflicts(
		ctx context.Context,
		gw *v1alpha1.KrakenDGateway,
		replace []v1alpha1.KrakenDEndpoint,
	) (configcheck.RouteConflicts, error)
	CheckRoot(ctx context.Context, r configcheck.Root, memo configcheck.Memo) (configcheck.Verdict, error)
	CheckGroup(ctx context.Context, g configcheck.Group, memo configcheck.Memo) (configcheck.Verdict, error)
	CheckEndpoint(
		ctx context.Context, u configcheck.EndpointUnit, memo configcheck.Memo,
	) (configcheck.EndpointVerdict, error)
}

// claimEndpoints returns the endpoints ac controls, found by the controller
// UID index, after adopting label-matched orphans the way a ReplicaSet adopts
// pods: an endpoint carrying both managed labels for ac, no controller
// reference and no deletion timestamp gets ac as its controller. An orphan
// that is in desired is left for writeEndpoint, which takes it over in the
// same write that updates it. An endpoint controlled by another object is
// never touched. Both lists are scoped to ac's namespace. Adoption failures
// are recorded in outcome.
func (r *KrakenDAutoConfigReconciler) claimEndpoints(
	ctx context.Context,
	ac *v1alpha1.KrakenDAutoConfig,
	desired []*v1alpha1.KrakenDEndpoint,
	outcome *endpointOutcome,
) ([]v1alpha1.KrakenDEndpoint, error) {
	var owned v1alpha1.KrakenDEndpointList
	if err := r.List(ctx, &owned, client.InNamespace(ac.Namespace),
		client.MatchingFields{fieldindex.EndpointController: string(ac.UID)},
	); err != nil {
		return nil, fmt.Errorf("listing controlled endpoints: %w", err)
	}
	var labelled v1alpha1.KrakenDEndpointList
	if err := r.List(ctx, &labelled, client.InNamespace(ac.Namespace),
		client.MatchingLabels{autoconfig.LabelAutoConfig: ac.Name, autoconfig.LabelAutoGenerated: "true"},
	); err != nil {
		return nil, fmt.Errorf("listing labelled endpoints: %w", err)
	}
	wanted := make(map[string]bool, len(desired))
	for _, ep := range desired {
		wanted[ep.Name] = true
	}
	// A cache lists in no particular order; adopt by name so the failures
	// of one pass read the same on every identical pass.
	slices.SortFunc(labelled.Items, func(a, b v1alpha1.KrakenDEndpoint) int {
		return strings.Compare(a.Name, b.Name)
	})
	controlled := owned.Items
	for i := range labelled.Items {
		orphan := &labelled.Items[i]
		if metav1.GetControllerOf(orphan) != nil || !orphan.DeletionTimestamp.IsZero() || wanted[orphan.Name] {
			continue
		}
		if err := controllerutil.SetControllerReference(ac, orphan, r.Scheme); err != nil {
			outcome.record(orphan, fmt.Errorf("adopting endpoint %s: %w", orphan.Name, err))
			continue
		}
		if err := r.Update(ctx, orphan); apierrors.IsNotFound(err) {
			// Deleted since the list: nothing left to adopt.
			continue
		} else if err != nil {
			outcome.record(orphan, fmt.Errorf("adopting endpoint %s: %w", orphan.Name, err))
			continue
		}
		controlled = append(controlled, *orphan)
	}
	return controlled, nil
}

// planEndpoints splits the work: writes are the desired endpoints that are
// missing from controlled or differ from their controlled copy, in desired
// order; stale are the controlled endpoints no longer desired, by name.
func planEndpoints(
	controlled []v1alpha1.KrakenDEndpoint,
	desired []*v1alpha1.KrakenDEndpoint,
) (writes []*v1alpha1.KrakenDEndpoint, stale []v1alpha1.KrakenDEndpoint) {
	byName := make(map[string]*v1alpha1.KrakenDEndpoint, len(controlled))
	for i := range controlled {
		byName[controlled[i].Name] = &controlled[i]
	}
	wanted := make(map[string]bool, len(desired))
	for _, ep := range desired {
		wanted[ep.Name] = true
		cur, ok := byName[ep.Name]
		if !ok || !labelsContain(cur.Labels, ep.Labels) || !endpointSpecEqual(cur.Spec, ep.Spec) {
			writes = append(writes, ep)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(byName)) {
		if !wanted[name] {
			stale = append(stale, *byName[name])
		}
	}
	return writes, stale
}

// labelsContain reports whether every label in want is set to the same value
// in have.
func labelsContain(have, want map[string]string) bool {
	for k, v := range want {
		if cur, ok := have[k]; !ok || cur != v {
			return false
		}
	}
	return true
}

// deleteEndpoint deletes a stale endpoint ac controls (claimEndpoints only
// returns those), preconditioned on its UID so a same-named replacement is
// never deleted. It reports whether this call deleted it; NotFound is not an
// error.
func (r *KrakenDAutoConfigReconciler) deleteEndpoint(
	ctx context.Context,
	ep *v1alpha1.KrakenDEndpoint,
) (bool, error) {
	err := r.Delete(ctx, ep, client.Preconditions{UID: &ep.UID})
	switch {
	case err == nil:
		return true, nil
	case apierrors.IsNotFound(err):
		return false, nil
	default:
		return false, fmt.Errorf("deleting endpoint %s: %w", ep.Name, err)
	}
}

// writeEndpoint creates or updates ep's live copy: it merges ep's labels into
// the existing ones, sets its spec and makes ac its controller. An endpoint
// of that name controlled by another object fails with
// controllerutil.AlreadyOwnedError. It returns the endpoint as the API server
// holds it after the write, status included.
func (r *KrakenDAutoConfigReconciler) writeEndpoint(
	ctx context.Context,
	ac *v1alpha1.KrakenDAutoConfig,
	ep *v1alpha1.KrakenDEndpoint,
) (controllerutil.OperationResult, *v1alpha1.KrakenDEndpoint, error) {
	live := &v1alpha1.KrakenDEndpoint{ObjectMeta: metav1.ObjectMeta{Name: ep.Name, Namespace: ep.Namespace}}
	op, err := controllerutil.CreateOrUpdate(ctx, r.Client, live, func() error {
		if live.Labels == nil {
			live.Labels = map[string]string{}
		}
		maps.Copy(live.Labels, ep.Labels)
		if !endpointSpecEqual(live.Spec, ep.Spec) {
			live.Spec = ep.Spec
		}
		return controllerutil.SetControllerReference(ac, live, r.Scheme)
	})
	if err != nil {
		return op, nil, fmt.Errorf("upserting endpoint %s: %w", ep.Name, err)
	}
	return op, live, nil
}

// rejection is why an endpoint was not written.
type rejection struct {
	endpoint        *v1alpha1.KrakenDEndpoint
	reason, message string
	// cause is the full error, for the log: message is cut for the status.
	cause error
}

// endpointOutcome is what one reconcileEndpoints call did and could not do.
type endpointOutcome struct {
	changes endpointChanges
	// transient holds adoption, write and delete errors worth retrying with
	// backoff.
	transient []error
	// raced holds Conflict and AlreadyExists write errors: this reconcile
	// acted on a stale cache and loses nothing by retrying soon.
	raced []error
	// rejected holds the endpoints left unwritten for a persistent reason,
	// keyed by name: the API server rejected them as invalid, or another
	// object controls their name. Their existing endpoints are held.
	rejected map[string]rejection
	// readiness summarizes the endpoints the AutoConfig controls afterwards.
	readiness endpointReadiness
}

// failed reports whether any claim or write failed.
func (o *endpointOutcome) failed() bool {
	return len(o.transient) > 0 || len(o.raced) > 0 || len(o.rejected) > 0
}

// record classifies a failed claim or write of ep: a Conflict or
// AlreadyExists lost a race, an Invalid rejection or a name another object
// controls is persistent, and anything else is retried with backoff.
func (o *endpointOutcome) record(ep *v1alpha1.KrakenDEndpoint, err error) {
	var owned *controllerutil.AlreadyOwnedError
	// The status names the endpoint already: leave out the wrap that says
	// which write failed.
	message := err.Error()
	if inner := errors.Unwrap(err); inner != nil {
		message = inner.Error()
	}
	switch {
	case apierrors.IsConflict(err) || apierrors.IsAlreadyExists(err):
		o.raced = append(o.raced, err)
	case apierrors.IsInvalid(err) || errors.As(err, &owned):
		o.rejected[ep.Name] = rejection{
			endpoint: ep, reason: v1alpha1.ReasonEndpointRejected, message: message, cause: err,
		}
	default:
		o.transient = append(o.transient, err)
	}
}

// endpointFailuresError is every failure of one endpoint pass. Error is the whole
// list, for the log and the returned error; Summary names the first few and
// counts the rest, for the status and the event.
type endpointFailuresError struct {
	errs []error
}

func (f endpointFailuresError) Error() string {
	return kerrors.NewAggregate(f.errs).Error()
}

// Summary names the first failures, as listed does.
func (f endpointFailuresError) Summary() string {
	messages := make([]string, len(f.errs))
	for i, err := range f.errs {
		messages[i] = err.Error()
	}
	return listed(messages)
}

// validatorUnavailableError marks a reconcileEndpoints failure caused by the
// gateway config check being unavailable (a transient condition).
type validatorUnavailableError struct{ err error }

func (e *validatorUnavailableError) Error() string { return "gateway config check: " + e.err.Error() }
func (e *validatorUnavailableError) Unwrap() error { return e.err }

// endpointFailureReason is the Synced reason for a reconcileEndpoints error:
// ValidatorUnavailable when the gateway config check could not run,
// EndpointReconcileFailed otherwise.
func endpointFailureReason(err error) string {
	var unavailable *validatorUnavailableError
	if errors.As(err, &unavailable) {
		return v1alpha1.ReasonValidatorUnavailable
	}
	return v1alpha1.ReasonEndpointReconcileFailed
}

// precheck returns the endpoints reconcileEndpoints would write that it must
// hold, keyed by name. A missing gateway renders nothing, so nothing is
// checked. It holds, in order:
//  1. on a CE gateway, the candidates that use Enterprise-only namespaces, as
//     EndpointRejected (the reason a refused write would give), never
//     checked: entry and backend namespaces are held without a write, while
//     other admission rules the config check cannot see cost one rejected
//     write per sync, which is held as EndpointRejected too;
//  2. the candidates that would newly clash in the router (routerClashes).
//     Its render replaces the stale endpoints by empty copies only when this
//     reconcile will also delete them: held is false and nothing was held
//     before. A hold keeps them, so step 4 looks again;
//  3. the candidates that fail validation on their own (judgeCandidates);
//  4. when step 2 or 3 held any, the candidates that would newly clash once
//     the held ones stay as stored and the stale endpoints stay (routerClashes
//     again, until no new clash appears).
//
// An error means a check could not run.
func (r *KrakenDAutoConfigReconciler) precheck(
	ctx context.Context,
	ac *v1alpha1.KrakenDAutoConfig,
	writes []*v1alpha1.KrakenDEndpoint,
	stale []v1alpha1.KrakenDEndpoint,
	order creationOrder,
	held bool,
) (_ map[string]rejection, retErr error) {
	ctx, span := tracing.Start(ctx, r.Tracer, "autoconfig.precheck")
	defer func() { tracing.End(span, retErr) }()
	rejected := map[string]rejection{}
	if len(writes) == 0 {
		return rejected, nil
	}
	var gw v1alpha1.KrakenDGateway
	gwKey := types.NamespacedName{
		Name:      ac.Spec.GatewayRef.Name,
		Namespace: ac.Spec.GatewayRef.ResolvedNamespace(ac.Namespace),
	}
	if err := r.Get(ctx, gwKey, &gw); err != nil {
		if apierrors.IsNotFound(err) {
			return rejected, nil
		}
		return nil, fmt.Errorf("getting gateway %s: %w", gwKey, err)
	}

	if gw.Spec.Edition == v1alpha1.EditionCE {
		for _, ep := range writes {
			if uses := ceIgnoredNamespaces(ep); len(uses) > 0 {
				message := fmt.Sprintf("not written: gateway %s runs CE, which ignores these Enterprise-only "+
					"namespaces: %s", gwKey, strings.Join(uses, ", "))
				rejected[ep.Name] = rejection{
					endpoint: ep, reason: v1alpha1.ReasonEndpointRejected, message: message, cause: errors.New(message),
				}
			}
		}
		writes = withoutHeld(writes, rejected)
	}

	clashes, err := r.routerClashes(ctx, &gw, writes, stale, order, !held && len(rejected) == 0)
	if err != nil {
		return nil, &validatorUnavailableError{err: err}
	}
	maps.Copy(rejected, clashes)
	writes = withoutHeld(writes, rejected)

	judged, err := r.judgeCandidates(ctx, ac, &gw, writes, order)
	if err != nil {
		return nil, &validatorUnavailableError{err: err}
	}
	maps.Copy(rejected, judged)
	if len(clashes) == 0 && len(judged) == 0 {
		return rejected, nil
	}
	// A hold keeps the stale endpoints (the sync deletes none) and leaves the
	// held candidate at its stored version, which the first clash render did
	// not model. Render again without the held until no new clash appears.
	for writes = withoutHeld(writes, judged); len(writes) > 0; writes = withoutHeld(writes, clashes) {
		clashes, err = r.routerClashes(ctx, &gw, writes, stale, order, false)
		if err != nil {
			return nil, &validatorUnavailableError{err: err}
		}
		if len(clashes) == 0 {
			break
		}
		maps.Copy(rejected, clashes)
	}
	return rejected, nil
}

// holdMessageLimit bounds a held candidate's own krakend output, in bytes, so
// that the whole message, with the words that introduce the output and the
// count of findings left out, fits the status without a cut mid-finding.
const holdMessageLimit = maxStatusMessageLen - len("fails krakend check on its own: ") - len(" (+999 more)")

// judgeCandidates holds each candidate that fails validation on its own,
// with its own message, in the order that runs the fewest checks:
//  1. the gateway root alone: when it fails, no candidate is to blame and
//     none is judged, so all are written;
//  2. the root with every candidate together (the group);
//  3. each candidate the group does not vouch for, on its own
//     (configcheck.CheckEndpoint): every one when the group fails, otherwise
//     those that lost an entry in the group's render (suspects).
//
// Other endpoints of the gateway are never rendered with a candidate, so
// their content can neither hold one nor reach its message. Every check
// holds one of CheckSlots and answers from the AutoConfig's verdict memo.
func (r *KrakenDAutoConfigReconciler) judgeCandidates(
	ctx context.Context,
	ac *v1alpha1.KrakenDAutoConfig,
	gw *v1alpha1.KrakenDGateway,
	candidates []*v1alpha1.KrakenDEndpoint,
	order creationOrder,
) (held map[string]rejection, err error) {
	held = map[string]rejection{}
	if len(candidates) == 0 {
		return held, nil
	}
	key := client.ObjectKeyFromObject(ac)
	pass := r.verdicts.begin(key)
	defer func() { r.verdicts.end(key, pass, err != nil) }()
	ceFallback := configcheck.CEFallback(gw)
	root, err := withCheckSlot(ctx, r.CheckSlots, func() (configcheck.Verdict, error) {
		return r.Checker.CheckRoot(ctx, configcheck.Root{Gateway: gw, CEFallback: ceFallback}, pass)
	})
	if err != nil || !root.OK {
		return held, err
	}
	group, err := withCheckSlot(ctx, r.CheckSlots, func() (configcheck.Verdict, error) {
		return r.Checker.CheckGroup(ctx, configcheck.Group{
			Gateway: gw, Endpoints: checkSet(candidates, nil, order, false), CEFallback: ceFallback,
		}, pass)
	})
	if err != nil {
		return held, err
	}
	for _, ep := range suspects(candidates, group) {
		v, err := withCheckSlot(ctx, r.CheckSlots, func() (configcheck.EndpointVerdict, error) {
			unit := configcheck.EndpointUnit{Gateway: gw, Endpoint: ep, CEFallback: ceFallback}
			return r.Checker.CheckEndpoint(ctx, unit, pass)
		})
		if err != nil {
			return nil, err
		}
		if !v.OK {
			held[ep.Name] = rejection{endpoint: ep, reason: v1alpha1.ReasonConfigValidationFailed,
				message: v.Message(holdMessageLimit), cause: errors.New(v.Message(math.MaxInt))}
		}
	}
	return held, nil
}

// suspects returns the candidates group does not vouch for
// (Verdict.Suspect).
func suspects(candidates []*v1alpha1.KrakenDEndpoint, group configcheck.Verdict) []*v1alpha1.KrakenDEndpoint {
	return slices.DeleteFunc(slices.Clone(candidates), func(ep *v1alpha1.KrakenDEndpoint) bool {
		return !group.Suspect(client.ObjectKeyFromObject(ep))
	})
}

// withCheckSlot runs check holding one of slots, and gives up when ctx ends
// while waiting. A nil slots runs check at once.
func withCheckSlot[T any](ctx context.Context, slots chan struct{}, check func() (T, error)) (T, error) {
	if slots != nil {
		select {
		case slots <- struct{}{}:
			defer func() { <-slots }()
		case <-ctx.Done():
			var zero T
			return zero, fmt.Errorf("waiting for an AutoConfig check slot: %w", ctx.Err())
		}
	}
	return check()
}

// routerClashesCappedMessage holds every candidate while the gateway's render
// stops resolving router clashes at its cap: a new clash cannot be told apart.
const routerClashesCappedMessage = "not written: " + configcheck.ClashesCapped

// routerClashes holds each candidate that, written, would take part in a
// router clash the gateway does not have now: an entry KrakenD's router
// cannot serve next to another endpoint's although their routes differ in
// shape. The candidate that loses the clash is held. A candidate that would
// keep an existing endpoint's entry out of the router is held too, so a write
// never makes another endpoint lose a route. The rendering is in process and
// holds no check slot. While the render stops resolving clashes at its cap, a
// new one cannot be told apart, so every candidate is held.
func (r *KrakenDAutoConfigReconciler) routerClashes(
	ctx context.Context,
	gw *v1alpha1.KrakenDGateway,
	writes []*v1alpha1.KrakenDEndpoint,
	stale []v1alpha1.KrakenDEndpoint,
	order creationOrder,
	withoutStale bool,
) (map[string]rejection, error) {
	held := map[string]rejection{}
	if len(writes) == 0 {
		return held, nil
	}
	before, err := r.Checker.Conflicts(ctx, gw, nil)
	if err != nil {
		return nil, err
	}
	after, err := r.Checker.Conflicts(ctx, gw, checkSet(writes, stale, order, withoutStale))
	if err != nil {
		return nil, err
	}
	if after.Capped {
		hold(held, writes, routerClashesCappedMessage, errors.New(routerClashesCappedMessage))
		return held, nil
	}
	candidates := make(map[types.NamespacedName]*v1alpha1.KrakenDEndpoint, len(writes))
	involving := make(map[types.NamespacedName]bool, len(writes))
	for _, ep := range writes {
		key := client.ObjectKeyFromObject(ep)
		candidates[key], involving[key] = ep, true
	}
	for _, c := range configcheck.NewClashes(before, after, involving) {
		ep := candidates[c.Loser]
		if ep == nil {
			ep = candidates[c.Winner]
		}
		hold(held, []*v1alpha1.KrakenDEndpoint{ep}, c.String(), errors.New(c.String()))
	}
	return held, nil
}

// withoutHeld returns eps less the endpoints held names, as a new slice.
func withoutHeld(eps []*v1alpha1.KrakenDEndpoint, held map[string]rejection) []*v1alpha1.KrakenDEndpoint {
	return slices.DeleteFunc(slices.Clone(eps), func(ep *v1alpha1.KrakenDEndpoint) bool {
		_, ok := held[ep.Name]
		return ok
	})
}

// hold records each endpoint in eps as failing the config check: message is
// for the status, cause the full text for the log.
func hold(rejected map[string]rejection, eps []*v1alpha1.KrakenDEndpoint, message string, cause error) {
	for _, ep := range eps {
		rejected[ep.Name] = rejection{
			endpoint: ep, reason: v1alpha1.ReasonConfigValidationFailed, message: message, cause: cause,
		}
	}
}

// ceIgnoredNamespaces lists each Enterprise-only extra_config namespace ep's
// entries and backends use, as "<field> <namespace>", with the keys CE drops
// when it honors the rest of the block. KrakenD CE accepts them in krakend
// check and ignores them, so the gateway config check cannot see them, and
// the endpoint webhook refuses them on a CE gateway.
func ceIgnoredNamespaces(ep *v1alpha1.KrakenDEndpoint) []string {
	var uses []string
	for i, e := range ep.Spec.Endpoints {
		entry := fmt.Sprintf("spec.endpoints[%d]", i)
		for _, d := range renderer.EEOnlyNamespacesIn(e.ExtraConfig, renderer.LevelEndpoint) {
			uses = append(uses, entry+".extraConfig "+d.String())
		}
		for j, be := range e.Backends {
			for _, d := range renderer.EEOnlyNamespacesIn(be.ExtraConfig, renderer.LevelBackend) {
				uses = append(uses, fmt.Sprintf("%s.backends[%d].extraConfig %s", entry, j, d.String()))
			}
		}
	}
	return uses
}

// checkSet is the replace set for one precheck round: the candidates, plus,
// when withoutStale, an empty copy of each stale endpoint, which renders no
// route and no schema. Each candidate carries the creationTimestamp the
// cluster gives it (order), because the renderer serves the oldest of the
// endpoints that share a route: a candidate left without one would win
// every route against the endpoints that exist.
func checkSet(
	candidates []*v1alpha1.KrakenDEndpoint,
	stale []v1alpha1.KrakenDEndpoint,
	order creationOrder,
	withoutStale bool,
) []v1alpha1.KrakenDEndpoint {
	set := make([]v1alpha1.KrakenDEndpoint, 0, len(candidates)+len(stale))
	for _, ep := range candidates {
		candidate := ep.DeepCopy()
		candidate.CreationTimestamp = order.timestamp(candidate.Name)
		set = append(set, *candidate)
	}
	if !withoutStale {
		return set
	}
	for i := range stale {
		gone := stale[i].DeepCopy()
		gone.Spec.Endpoints = nil
		gone.Spec.ComponentSchemas = nil
		set = append(set, *gone)
	}
	return set
}

// creationOrder is the order in which the renderer serves endpoints that share
// a route: the oldest creationTimestamp first (to the second), then the name.
// It knows the endpoints that exist; one it does not know is not yet created
// and sorts after every one that does (configcheck.NotYetCreated).
type creationOrder map[string]int64

// newCreationOrder records the creation time of each of existing.
func newCreationOrder(existing []v1alpha1.KrakenDEndpoint) creationOrder {
	order := make(creationOrder, len(existing))
	for i := range existing {
		order[existing[i].Name] = existing[i].CreationTimestamp.Unix()
	}
	return order
}

// compare orders two endpoint names as the renderer serves them.
func (o creationOrder) compare(a, b string) int {
	return cmp.Or(cmp.Compare(o.createdAt(a), o.createdAt(b)), strings.Compare(a, b))
}

func (o creationOrder) createdAt(name string) int64 {
	if t, ok := o[name]; ok {
		return t
	}
	return configcheck.NotYetCreated.Unix()
}

// withUncontrolled returns controlled plus the stored copy of each desired
// endpoint that exists and that no object controls: a label-matched orphan
// that writeEndpoint takes over, or an endpoint of that name nobody labelled.
// The cluster keeps the creation time of both, so the order must know it. An
// endpoint another object controls is left out: writeEndpoint refuses it, so
// ours never takes its age. A name that is not found is new. Any other read error leaves the name unknown, as
// a new one, and is logged: it cannot fail the sync.
func (r *KrakenDAutoConfigReconciler) withUncontrolled(
	ctx context.Context,
	controlled []v1alpha1.KrakenDEndpoint,
	desired []*v1alpha1.KrakenDEndpoint,
) []v1alpha1.KrakenDEndpoint {
	known := make(map[string]bool, len(controlled))
	for i := range controlled {
		known[controlled[i].Name] = true
	}
	all := slices.Clone(controlled)
	for _, ep := range desired {
		if known[ep.Name] {
			continue
		}
		var stored v1alpha1.KrakenDEndpoint
		err := r.Get(ctx, client.ObjectKeyFromObject(ep), &stored)
		switch {
		case err == nil:
			if metav1.GetControllerOf(&stored) == nil {
				all = append(all, stored)
			}
		case !apierrors.IsNotFound(err):
			logf.FromContext(ctx).V(1).Info("treating the endpoint as new in the creation order",
				"endpoint", ep.Name, "error", err.Error())
		}
	}
	return all
}

// timestamp is the creationTimestamp the cluster gives the endpoint name:
// its own when it exists, otherwise one after every existing endpoint's.
func (o creationOrder) timestamp(name string) metav1.Time {
	return metav1.NewTime(time.Unix(o.createdAt(name), 0))
}

// routeCollisions returns, keyed by name, the desired endpoints that lose
// their route to another desired endpoint. Endpoints are grouped by method and
// route shape (renderer.ConflictKey), the way the gateway's router tells
// routes apart: paths that differ only in parameter names or repeated slashes
// share a route, and only one of them is served. Stale endpoints take no part:
// while an operation is renamed its new endpoint and the old one share a route
// until the old one is deleted. The survivor of a group is the one the
// renderer serves.
func routeCollisions(
	desired []*v1alpha1.KrakenDEndpoint,
	existing []v1alpha1.KrakenDEndpoint,
) map[string]rejection {
	groups := map[string][]*v1alpha1.KrakenDEndpoint{}
	for _, ep := range desired {
		if len(ep.Spec.Endpoints) == 0 {
			continue
		}
		e := ep.Spec.Endpoints[0]
		key := renderer.RouteKey(e.Method, e.Endpoint)
		groups[key] = append(groups[key], ep)
	}
	order := newCreationOrder(existing)
	collisions := map[string]rejection{}
	for _, group := range groups {
		slices.SortFunc(group, func(a, b *v1alpha1.KrakenDEndpoint) int {
			return order.compare(a.Name, b.Name)
		})
		survivor := group[0]
		for _, ep := range group[1:] {
			e, winner := ep.Spec.Endpoints[0], survivor.Spec.Endpoints[0]
			message := renderer.RouteClashDetail(e.Method, e.Endpoint, winner.Endpoint, survivor.Name)
			hold(collisions, []*v1alpha1.KrakenDEndpoint{ep}, message, errors.New(message))
		}
	}
	return collisions
}

// reconcileEndpoints converges the KrakenDEndpoints ac controls to desired.
// It adopts label-matched orphans, runs the gateway config check over the
// endpoints it would write, writes every endpoint that passes (attempting all
// of them, whatever fails), and only then, when held is false and nothing
// failed, deletes the endpoints no longer desired, so a failure never takes a
// route off the gateway (make-before-break). held is true when some operation
// failed before generation: its endpoint is not in desired and must not be
// deleted. An error means the pass could not start: listing failed or the
// config check could not run. The outcome's readiness summarizes the
// endpoints ac controls afterwards: held ones keep their last-good endpoint,
// and a written one is judged from the object its write returned.
func (r *KrakenDAutoConfigReconciler) reconcileEndpoints(
	ctx context.Context,
	ac *v1alpha1.KrakenDAutoConfig,
	desired []*v1alpha1.KrakenDEndpoint,
	held bool,
) (_ endpointOutcome, retErr error) {
	ctx, span := tracing.Start(ctx, r.Tracer, "autoconfig.endpoints")
	defer func() { tracing.End(span, retErr) }()
	outcome := endpointOutcome{rejected: map[string]rejection{}}
	controlled, err := r.claimEndpoints(ctx, ac, desired, &outcome)
	if err != nil {
		return outcome, err
	}
	writes, stale := planEndpoints(controlled, desired)
	// An endpoint that loses its route to another is held whether or not it
	// would be written. The holds go in before the check, so it sees the stale
	// endpoints as they stay and checks only the endpoints still to be written.
	existing := r.withUncontrolled(ctx, controlled, desired)
	maps.Copy(outcome.rejected, routeCollisions(desired, existing))
	writes = withoutHeld(writes, outcome.rejected)
	checked, err := r.precheck(ctx, ac, writes, stale, newCreationOrder(existing),
		held || outcome.failed() || recursRejection(ac, writes))
	if err != nil {
		return outcome, err
	}
	maps.Copy(outcome.rejected, checked)
	// What ac controls once the writes are in: a written endpoint is judged
	// from the object the write returned, so one that was created or whose
	// spec changed reads Pending, and one that only gained a controller or
	// labels keeps the readiness its endpoint controller last reported.
	after := make(map[string]v1alpha1.KrakenDEndpoint, len(controlled)+len(writes))
	for _, ep := range controlled {
		after[ep.Name] = ep
	}
	for _, ep := range writes {
		if _, ok := outcome.rejected[ep.Name]; ok {
			continue // held by the config check
		}
		op, live, err := r.writeEndpoint(ctx, ac, ep)
		if err != nil {
			outcome.record(ep, err)
			continue
		}
		outcome.changes.count(op)
		after[ep.Name] = *live
	}

	gone := map[string]bool{}
	if !held && !outcome.failed() {
		for i := range stale {
			deleted, err := r.deleteEndpoint(ctx, &stale[i])
			if err != nil {
				outcome.record(&stale[i], err)
				continue
			}
			if deleted {
				outcome.changes.deleted++
			}
			gone[stale[i].Name] = true
		}
	}
	outcome.readiness = summarizeReadiness(slices.Collect(maps.Values(after)), gone)
	return outcome, nil
}

// recursRejection reports whether a write in this pass names an endpoint the
// last status recorded as EndpointRejected. The API server rejects it again,
// so the pass will not delete the stale endpoints and the check must model
// them as staying.
func recursRejection(ac *v1alpha1.KrakenDAutoConfig, writes []*v1alpha1.KrakenDEndpoint) bool {
	for _, f := range ac.Status.FailedOperations {
		if f.Reason != v1alpha1.ReasonEndpointRejected {
			continue
		}
		if slices.ContainsFunc(writes, func(ep *v1alpha1.KrakenDEndpoint) bool { return ep.Name == f.Endpoint }) {
			return true
		}
	}
	return false
}

// endpointSpecEqual reports whether a and b serialize to the same JSON value.
// Embedded raw JSON (extraConfig, componentSchemas) is compared by value, so
// key order, whitespace, escaping and number formatting do not count: the API
// server re-encodes it differently from how the generator emits it, and a
// byte comparison would update every generated endpoint on every reconcile.
func endpointSpecEqual(a, b v1alpha1.KrakenDEndpointSpec) bool {
	var values [2]any
	for i, spec := range []v1alpha1.KrakenDEndpointSpec{a, b} {
		raw, err := json.Marshal(spec)
		if err != nil {
			return false
		}
		if err := json.Unmarshal(raw, &values[i]); err != nil {
			return false
		}
	}
	return reflect.DeepEqual(values[0], values[1])
}
